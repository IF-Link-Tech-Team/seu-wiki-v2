const MP_PREFIX = "公众号";

function mpCollection(tags: readonly string[]): string {
  if (tags.includes("校友")) return "校友会公众号";
  if (tags.includes("科研机构")) return "课题组与学术公众号";
  if (tags.includes("竞赛")) return "竞赛与赛事公众号";
  if (tags.includes("校级")) return "校级公众号";
  return "其他公众号";
}

function sourceGroup(tags: readonly string[]): SourceGroup | null {
  for (const group of SOURCE_GROUPS) if (group !== MP_PREFIX && tags.includes(group)) return group;
  return Object.entries(LEGACY_GROUPS).find(([tag]) => tags.includes(tag))?.[1] ?? null;
}

/** 由信源名和标签得出它在筛选面板里的位置：分组、单位（一级）、栏目（二级）。 */
export function sourceOrg(name: string, tags: readonly string[]): { group: SourceGroup | null; org: string; label: string } {
  const dot = name.indexOf("·");
  const prefix = dot < 0 ? name : name.slice(0, dot);
  const rest = dot < 0 ? name : name.slice(dot + 1);
  if (prefix === MP_PREFIX) {
    for (const [group, accounts] of Object.entries(MP_ORGS)) {
      const org = accounts[rest];
      if (org) return { group: group as SourceGroup, org, label: group === MP_PREFIX ? rest : name };
    }
    return { group: MP_PREFIX, org: mpCollection(tags), label: rest };
  }
  return { group: sourceGroup(tags), org: ORG_ALIASES[prefix] ?? prefix, label: rest };
}
